// Voice clip core shared by the CLI (generate.mjs) and the Voice Studio (studio.mjs).
// Every function takes ctx = { root, synthesize? } and reads state fresh from disk;
// every write re-reads, applies its change and writes back, so the CLI and the studio
// never undo each other. See docs/VOICE.md.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const CONCURRENCY = 8;

// Same rule as src/sdk/speech/clipKey.ts (voiceClips.test.ts catches drift).
export const clipKey = (lang, text) => `${lang}:${text.normalize('NFC').trim()}`;
export const slug = (key) => `${key.slice(0, 2)}-${createHash('sha1').update(key).digest('hex').slice(0, 10)}`;
const today = () => new Date().toISOString().slice(0, 10);

export const paths = (root) => ({
  config: join(root, 'scripts/voice/voice.config.json'),
  catalog: join(root, 'scripts/voice/catalog.json'),
  flags: join(root, 'scripts/voice/flags.json'),
  takes: join(root, 'scripts/voice/.takes'),
  clips: join(root, 'src/sdk/assets/audio/speech'),
  lock: join(root, 'src/sdk/speech/clips.lock.json'),
  map: join(root, 'src/sdk/speech/clips.generated.ts'),
});

const readJson = (file, fallback) => (existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : fallback);
const sortKeys = (obj) => Object.fromEntries(Object.keys(obj).sort().map((k) => [k, obj[k]]));

export function parseArgs(argv) {
  const args = { dryRun: false, redo: new Set(), pick: new Map() };
  const value = (flag, i) => {
    if (argv[i] === undefined || argv[i].startsWith('--')) throw new Error(`${flag} needs a value, e.g. ${flag} "ar:كَاف. كُرَة"`);
    return argv[i];
  };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--dry-run') args.dryRun = true;
    else if (a === '--redo') args.redo.add(value(a, ++i).normalize('NFC').trim());
    else if (a === '--pick') {
      const m = value(a, ++i).match(/^(.+)=([1-9]\d*)$/);
      if (!m) throw new Error(`--pick takes "<key>=<take number>", e.g. --pick "ar:كَاف. كُرَة=2"`);
      args.pick.set(m[1].normalize('NFC').trim(), Number(m[2]));
    } else throw new Error(`unknown argument: ${a}`);
  }
  return args;
}

/** Everything on disk, fresh: config, catalog games + lines (keyed), lock, flags. */
export function readState({ root }) {
  const p = paths(root);
  const catalog = readJson(p.catalog, { games: [], lines: [] });
  return {
    config: readJson(p.config, null),
    games: catalog.games,
    lines: new Map(catalog.lines.map((l) => [clipKey(l.lang, l.text), l])),
    lock: readJson(p.lock, {}),
    flags: readJson(p.flags, {}),
  };
}

function writeMap(root, lock) {
  const lines = Object.keys(lock).map((k) => `  ${JSON.stringify(k)}: require('../assets/audio/speech/${lock[k].file}'),`);
  writeFileSync(
    paths(root).map,
    `// Generated by scripts/voice/generate.mjs — do not edit.\n// Bundled voice clips keyed by clipKey(lang, text); see docs/VOICE.md.\nexport const CLIPS: Record<string, number> = {\n${lines.join('\n')}${lines.length ? '\n' : ''}};\n`,
  );
}

/** Read-modify-write of the lock (and the generated map with it). */
function updateLock(root, mutate) {
  const lock = readJson(paths(root).lock, {});
  mutate(lock);
  const sorted = sortKeys(lock);
  writeFileSync(paths(root).lock, JSON.stringify(sorted, null, 1) + '\n');
  writeMap(root, sorted);
}

function updateFlags(root, mutate) {
  const flags = readJson(paths(root).flags, {});
  mutate(flags);
  writeFileSync(paths(root).flags, JSON.stringify(sortKeys(flags), null, 1) + '\n');
}

/** A clip's takes as { n, file }, numbered by file name (take-3.mp3 is take 3 even if take 2 failed). */
export function takeFiles(root, key, dir = join(paths(root).takes, slug(key))) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .map((f) => ({ n: Number(f.match(/^take-(\d+)\.mp3$/)?.[1]), file: join(dir, f) }))
    .filter((t) => t.n > 0)
    .sort((a, b) => a.n - b.n);
}

/** One row per catalog phrase, for the studio and the CLI. */
export function status(ctx) {
  const { config, lines, lock, flags } = readState(ctx);
  return [...lines].map(([key, l]) => {
    const entry = lock[key];
    return {
      key,
      lang: l.lang,
      text: l.text,
      uses: l.uses ?? [],
      state: !entry ? 'missing' : entry.voice !== config.voices[l.lang] ? 'stale' : 'ok',
      clip: entry ? { file: entry.file, take: entry.take, durationS: entry.durationS } : null,
      takes: takeFiles(ctx.root, key).map((t) => ({ n: t.n, file: t.file })),
      flag: flags[key] ?? null,
      chars: l.text.length * config.takes,
    };
  });
}

// ---------- audio ----------
const ffmpeg = (args) => execFileSync('ffmpeg', ['-y', '-v', 'error', ...args], { stdio: ['ignore', 'ignore', 'pipe'] });
export const duration = (f) => Number(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', f]).toString());

/** Mean volume of the speech only (silence trimmed), like the SFX "active RMS". */
function activeDb(file) {
  const trim = 'silenceremove=start_periods=1:start_threshold=-45dB:stop_periods=-1:stop_threshold=-45dB:stop_duration=0.1';
  const out = execFileSync('sh', ['-c', `ffmpeg -v info -i "${file}" -af "${trim},volumedetect" -f null - 2>&1 | grep mean_volume || true`]).toString();
  const m = out.match(/(-?[\d.]+) dB/);
  if (!m) throw new Error(`no audio level for ${file}`);
  return Number(m[1]);
}

/** Normalize a take into the committed clip. */
function finalize(config, take, out) {
  const gain = config.loudness.rmsDb - activeDb(take);
  const limit = (10 ** (config.loudness.peakDb / 20)).toFixed(3);
  const { sampleRate, codec, bitrate } = config.format;
  ffmpeg(['-i', take, '-af', `volume=${gain.toFixed(2)}dB,alimiter=limit=${limit}:level=false`, '-ac', '1', '-ar', String(sampleRate), '-c:a', codec, '-b:a', bitrate, out]);
}

/** Make take n of `key` the clip in the app. Throws when it can't; the lock then stays as it was. */
export function pickTake(ctx, key, n) {
  const { root } = ctx;
  const { config, lines } = readState(ctx);
  const line = lines.get(key);
  if (!line) throw new Error(`not in catalog: ${key}`);
  const takes = takeFiles(root, key);
  const take = takes.find((t) => t.n === n);
  if (!take) throw new Error(`no take ${n} (have ${takes.map((t) => t.n).join(', ') || 'none'}; run --redo first)`);
  const file = `${slug(key)}.m4a`;
  mkdirSync(paths(root).clips, { recursive: true });
  const out = join(paths(root).clips, file);
  finalize(config, take.file, out);
  const entry = { file, voice: config.voices[line.lang], take: n, durationS: Number(duration(out).toFixed(2)), generatedAt: today() };
  updateLock(root, (lock) => {
    lock[key] = entry;
  });
  return entry;
}

// ---------- recording ----------
async function request(config, lang, text) {
  const voice = config.voices[lang];
  // Key in a header, not the URL, so it stays out of proxy and access logs.
  const res = await fetch('https://texttospeech.googleapis.com/v1/text:synthesize', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', 'X-Goog-Api-Key': process.env.GOOGLE_TTS_API_KEY },
    body: JSON.stringify({ input: { text }, voice: { languageCode: voice.split('-').slice(0, 2).join('-'), name: voice }, audioConfig: { audioEncoding: 'MP3' } }),
  });
  if (!res.ok) throw new Error(`HTTP ${res.status}: ${(await res.text()).slice(0, 200)}`);
  return Buffer.from((await res.json()).audioContent, 'base64');
}

/** The Google call; rate limits (429) are waited out instead of failing the run. */
export function googleSynthesize(config) {
  const synth = async (lang, text, attempt = 1) => {
    try {
      return await request(config, lang, text);
    } catch (e) {
      if (!e.message.startsWith('HTTP 429') || attempt >= 6) throw e;
      await new Promise((r) => setTimeout(r, 15000 * attempt));
      return synth(lang, text, attempt + 1);
    }
  };
  return synth;
}

async function pool(jobs, limit) {
  const queue = [...jobs];
  await Promise.all(Array.from({ length: limit }, async () => {
    while (queue.length) await queue.shift()();
  }));
}

/**
 * Record `takes` fresh takes for each key, then install the median-length one.
 * A clip already in the app is only replaced by a full set; a new phrase takes
 * whatever was recorded. Never throws for one key — failures are reported.
 * onProgress fires as each take lands ({ phase: 'takes', done, total }) and as each
 * phrase is installed ({ phase: 'phrases', key, done, total }).
 */
export async function recordTakes(ctx, requested, onProgress = () => {}) {
  const { root } = ctx;
  const keys = [...new Set(requested)];
  const { config, lines, lock } = readState(ctx);
  const synthesize = ctx.synthesize ?? googleSynthesize(config);
  const written = [];
  const failed = [];
  const fresh = (key) => join(paths(root).takes, `${slug(key)}.new`);

  const jobs = [];
  let takesDone = 0;
  const takesTotal = keys.filter((k) => lines.has(k)).length * config.takes;
  for (const key of keys) {
    const line = lines.get(key);
    if (!line) {
      failed.push(`${key}: not in catalog`);
      continue;
    }
    const dir = fresh(key);
    rmSync(dir, { recursive: true, force: true });
    mkdirSync(dir, { recursive: true });
    for (let n = 1; n <= config.takes; n++) {
      jobs.push(async () => {
        try {
          writeFileSync(join(dir, `take-${n}.mp3`), await synthesize(line.lang, line.text));
        } catch (e) {
          failed.push(`${key} take ${n}: ${e.message}`);
        }
        onProgress({ phase: 'takes', done: ++takesDone, total: takesTotal });
      });
    }
  }
  await pool(jobs, CONCURRENCY);

  let done = keys.filter((k) => !lines.has(k)).length;
  for (const key of keys.filter((k) => lines.has(k))) {
    const got = takeFiles(root, key, fresh(key)).length;
    if (got === config.takes || (!lock[key] && got > 0)) {
      rmSync(join(paths(root).takes, slug(key)), { recursive: true, force: true });
      renameSync(fresh(key), join(paths(root).takes, slug(key)));
      try {
        // Auto-pick the median-length take; outliers are the rushed or drawn-out ones.
        const byLength = takeFiles(root, key).map((t) => ({ n: t.n, d: duration(t.file) })).sort((a, b) => a.d - b.d);
        pickTake(ctx, key, byLength[Math.floor((byLength.length - 1) / 2)].n);
        written.push(key);
      } catch (e) {
        failed.push(`${key}: ${e.message}`);
      }
    } else {
      rmSync(fresh(key), { recursive: true, force: true });
      if (lock[key]) failed.push(`${key}: only ${got}/${config.takes} takes recorded — kept the current clip`);
    }
    onProgress({ phase: 'phrases', key, done: ++done, total: keys.length });
  }
  return { written, failed };
}

/** Remove clips, lock entries and flags whose phrase left the catalog. Returns the removed keys. */
export function prune(ctx) {
  const { root } = ctx;
  const { lines } = readState(ctx);
  const removed = [];
  updateLock(root, (lock) => {
    for (const key of Object.keys(lock)) {
      if (lines.has(key)) continue;
      rmSync(join(paths(root).clips, lock[key].file), { force: true });
      delete lock[key];
      removed.push(key);
    }
  });
  updateFlags(root, (flags) => {
    for (const key of Object.keys(flags)) if (!lines.has(key)) delete flags[key];
  });
  return removed;
}

/** Flag a clip with a note for Claude, or clear it with null. Only the owner clears a flag. */
export function setFlag(ctx, key, note) {
  updateFlags(ctx.root, (flags) => {
    if (note === null) delete flags[key];
    else flags[key] = { note, at: today() };
  });
}

/** Claude's answer to a flag: what was changed, so the owner knows what to re-check. */
export function replyFlag(ctx, key, reply) {
  updateFlags(ctx.root, (flags) => {
    if (!flags[key]) throw new Error(`not flagged: ${key}`);
    flags[key] = { ...flags[key], reply, repliedAt: today() };
  });
}
