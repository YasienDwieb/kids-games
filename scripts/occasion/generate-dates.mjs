#!/usr/bin/env node
/**
 * Writes src/sdk/occasion/dates.generated.ts: the Gregorian windows of Ramadan,
 * Eid al-Fitr and Eid al-Adha for a range of Hijri years, from the Umm al-Qura
 * calendar in Node's ICU (`Intl` calendar `islamic-umalqura`).
 *
 * The app never computes these at runtime (Hermes's Hijri support is unreliable
 * on Android). Moon sighting can shift a date by a day per country; the content
 * config's `themes.dates` overrides a window when it does.
 *
 *   node scripts/occasion/generate-dates.mjs [fromAH=1448] [toAH=1455]
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const [from = 1448, to = 1455] = process.argv.slice(2).map(Number);
const fmt = new Intl.DateTimeFormat('en-u-ca-islamic-umalqura', {
  year: 'numeric', month: 'numeric', day: 'numeric', timeZone: 'UTC',
});
if (fmt.resolvedOptions().calendar !== 'islamic-umalqura') {
  throw new Error('This Node build has no islamic-umalqura calendar (needs full ICU).');
}

const hijriOf = (d) => {
  const parts = Object.fromEntries(fmt.formatToParts(d).map((p) => [p.type, p.value]));
  return { y: Number(parts.year), m: Number(parts.month), d: Number(parts.day) };
};
const iso = (d) => d.toISOString().slice(0, 10);
const DAY = 86400000;

// Walk every day from a little before the first year to after the last.
const startGreg = Date.UTC(2026, 0, 1);
const days = [];
for (let t = startGreg; ; t += DAY) {
  const h = hijriOf(new Date(t));
  if (h.y > to) break;
  if (h.y >= from) days.push({ date: iso(new Date(t)), ...h });
}

const pick = (y, m, dFrom, dTo) => {
  const inRange = days.filter((x) => x.y === y && x.m === m && x.d >= dFrom && (dTo == null || x.d <= dTo));
  if (inRange.length === 0) throw new Error(`no days for ${y}/${m}`);
  return { start: inRange[0].date, end: inRange[inRange.length - 1].date };
};

const table = { ramadan: [], 'eid-al-fitr': [], 'eid-al-adha': [] };
for (let y = from; y <= to; y++) {
  table.ramadan.push({ ah: y, ...pick(y, 9, 1) }); // whole of Ramadan
  table['eid-al-fitr'].push({ ah: y, ...pick(y, 10, 1, 3) }); // 1–3 Shawwal
  table['eid-al-adha'].push({ ah: y, ...pick(y, 12, 9, 13) }); // Arafah + Eid days
}

const row = ({ ah, start, end }) => `    { start: '${start}', end: '${end}' }, // ${ah} AH`;
const out = `// GENERATED by scripts/occasion/generate-dates.mjs from the Umm al-Qura calendar
// (Node ICU \`islamic-umalqura\`). Do not edit by hand; re-run the script.
// Spot-check against https://www.ummulqura.org.sa when regenerating.
import type { DateWindow, OccasionId } from '@/sdk/content/types';

/** Hijri years covered: ${from}–${to} AH. */
export const OCCASION_TABLE_RANGE = { fromAH: ${from}, toAH: ${to} } as const;

export const OCCASION_TABLE: Record<OccasionId, readonly DateWindow[]> = {
  ramadan: [
${table.ramadan.map(row).join('\n')}
  ],
  'eid-al-fitr': [
${table['eid-al-fitr'].map(row).join('\n')}
  ],
  'eid-al-adha': [
${table['eid-al-adha'].map(row).join('\n')}
  ],
};
`;

const target =
  process.env.OCCASION_DATES_OUT ??
  join(dirname(fileURLToPath(import.meta.url)), '../../src/sdk/occasion/dates.generated.ts');
writeFileSync(target, out);
console.log(`wrote ${target}`);
